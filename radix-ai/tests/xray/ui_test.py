# python3 tests/xray/ui_test.py   (needs Playwright). Runs the pages in DEMO MODE. The test image is a drawn placeholder, not a real X-ray.
import functools, http.server, os, sys, tempfile, threading
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHOTS = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=ROOT))
threading.Thread(target=srv.serve_forever, daemon=True).start()
URL = f'http://127.0.0.1:{srv.server_port}/'
bad = []
def ok(name, cond):
    print(('pass ' if cond else 'FAIL ') + name)
    if not cond: bad.append(name)
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2)
    ctx.route('**/js/config.js', lambda r: r.fulfill(content_type='text/javascript', body="const SUPABASE_URL='https://YOUR-PROJECT.supabase.co',SUPABASE_ANON_KEY='YOUR-ANON-KEY';"))  # force DEMO mode
    ctx.route(lambda u: not u.startswith(URL) and u.startswith('http'), lambda r: r.abort())
    pg = ctx.new_page(); errors = []
    pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.on('console', lambda m: errors.append(m.text) if 'Content Security Policy' in m.text and 'fonts' not in m.text and 'jsdelivr' not in m.text else None)
    pg.goto(URL + 'xray/index.html')
    img = os.path.join(tempfile.mkdtemp(), 'placeholder.png')
    maker = ctx.new_page(); maker.set_viewport_size({'width': 700, 'height': 800})
    maker.set_content('<body style="margin:0;background:#0b0d0e;color:#ccc;font:28px sans-serif;display:flex;align-items:center;justify-content:center;height:100vh"><div style="border:6px solid #999;border-radius:40%;width:60%;height:70%;display:flex;align-items:center;justify-content:center;text-align:center">TEST PLACEHOLDER<br>not an X-ray</div>')
    maker.screenshot(path=img); maker.close()
    pg.click('#go'); ok('empty form shows an error', pg.inner_text('#ferr') != '')
    pg.screenshot(path=SHOTS + '/1-upload.png', full_page=True)
    pg.fill('#name', '<img src=x onerror=window.pwned=1>'); pg.fill('#phone', '9800000000'); pg.fill('#age', '34')
    pg.select_option('#sex', 'female'); pg.select_option('#part', 'chest'); pg.select_option('#side', 'na'); pg.set_input_files('#file', img)
    ok('no image shown before scanning', pg.locator('#scan').is_hidden())
    pg.click('#go'); ok('consent is required', 'consent' in pg.inner_text('#ferr'))
    pg.check('#consent'); pg.click('#go'); pg.wait_for_selector('#scan:not([hidden])'); pg.wait_for_timeout(1000)
    ok('image visible while scanning', pg.evaluate('document.querySelector("#canvas").width') > 0)
    pg.screenshot(path=SHOTS + '/2-scanning.png')
    pg.wait_for_selector('#done:not([hidden])', timeout=15000)
    ok('image wiped after scan', pg.evaluate('[canvas.width, canvas.height, document.querySelector("#file").files.length, document.querySelectorAll("img").length].join()') == '0,0,0,0')
    store = pg.evaluate('JSON.stringify([{...localStorage}, {...sessionStorage}])')
    ok('no image data in browser storage', 'base64' not in store and '/9j/' not in store and len(store) < 5000)
    ref, code = pg.inner_text('#dref'), pg.inner_text('#dcode')
    pg.screenshot(path=SHOTS + '/3-done.png', full_page=True)
    def look():
        pg.click('#t-report'); pg.fill('#lref', ref); pg.fill('#lcode', code); pg.click('#lform button'); pg.wait_for_selector('#result .card')
        return pg.inner_text('#result')
    ok('patient sees waiting, not findings', 'Waiting for doctor review' in look() and 'SAMPLE' not in pg.inner_text('#result'))
    doc = ctx.new_page(); doc.on('pageerror', lambda e: errors.append(str(e))); doc.set_viewport_size({'width': 900, 'height': 900})
    doc.goto(URL + 'xray/review.html'); doc.fill('#email', 'd@x.com'); doc.fill('#pass', 'x'); doc.click('#login button'); doc.wait_for_selector('.row')
    doc.click('.row'); doc.wait_for_selector('#detail fieldset')
    doc.screenshot(path=SHOTS + '/4-doctor-review.png', full_page=True)
    f = doc.locator('input[type=file]'); f.set_input_files(img); doc.wait_for_selector('text=Same file as the one scanned')
    ok('original file matches fingerprint', True)
    other = img + '.2.png'; open(other, 'wb').write(open(img, 'rb').read() + b'x'); f.set_input_files(other); doc.wait_for_selector('text=NOT the same file')
    ok('different file is flagged', True)
    doc.click('text=Approve and release to patient'); ok('release blocked without confirmation', 'Tick the box' in doc.inner_text('#detail .err[role=alert]'))
    doc.get_by_label('Impression').fill('Doctor-edited impression (demo test).')
    doc.get_by_role('checkbox').check(); doc.click('text=Approve and release to patient'); doc.wait_for_selector('#list:not([hidden]) >> text=Nothing here')
    pg.click('#lform button'); pg.wait_for_selector('.sign')
    text = pg.inner_text('#result')
    ok('patient sees the doctor edit, reviewer and AI disclosure', 'Doctor-edited impression' in text and 'DEMO-000' in text and 'AI was used' in text)
    pg.screenshot(path=SHOTS + '/5-patient-report.png', full_page=True)
    ok('typed HTML did not run', pg.evaluate('window.pwned') is None and doc.evaluate('window.pwned') is None)
    ok('no sideways scrolling on phone', pg.evaluate('document.documentElement.scrollWidth') <= 390)
    ok('no JavaScript or policy errors', not errors)
    if errors: print(errors)
    # failure path: the service errors -> the image must still be wiped
    pg.click('#t-scan'); pg.click('#again'); pg.evaluate('() => { api.analyze = () => Promise.reject(new Error("Service down.")); }')
    pg.fill('#name', 'Test'); pg.fill('#phone', '9800000000'); pg.fill('#age', '34'); pg.select_option('#sex', 'male'); pg.select_option('#part', 'chest'); pg.select_option('#side', 'na'); pg.set_input_files('#file', img); pg.check('#consent'); pg.click('#go')
    pg.wait_for_selector('text=Service down.')
    ok('image wiped after a failed scan', pg.evaluate('canvas.width + document.querySelector("#file").files.length') == 0 and pg.locator('#scan').is_hidden())
    b.close()
srv.shutdown()
print('screenshots:', SHOTS); print(len(bad), 'failed'); sys.exit(1 if bad else 0)
